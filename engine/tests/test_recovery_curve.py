"""§P7-15's recovery-versus-amplitude curve: the estimator, not the pipeline.

The pipeline is `mine_session.run` and the plant machinery is `gate_r1`, both
already covered. What is new here is the ARITHMETIC that turns 120 binomial
observations into the sentence "the formula is (or is not) anti-conservative by
Nx" -- and a sign or scale error there would produce a confident wrong answer to
the exact question §P7-15 asked. So: the predicted curve is pinned against the
ledger's own published values, the estimator is pinned by recovering a known
effective floor from data generated under it, and the degenerate cases are
pinned to report BOUNDS rather than point estimates.
"""

import math

import numpy as np
import pytest

from engine import floors
from engine import gate_r1 as G
