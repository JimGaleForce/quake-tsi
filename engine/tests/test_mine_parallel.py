"""EQ-24 miner v2 throughput layer: parallelism, RNG policy and the ladder.

The four things this file exists to prevent:

  a. a "speedup" that quietly changed the sequential numbers. `--jobs 1` must be
     the v1 code path to the last bit, so the v1 inner loops are RE-STATED VERBATIM
     here and compared against the refactored task bodies. If someone edits
     `glm_task` and the pin still passes, the edit was genuinely behaviour-neutral.
  b. a parallel result that depends on how the pool happened to schedule. Same
     inputs at --jobs 2 and --jobs 4 must give the same numbers, bit for bit.
  c. a ladder p-value that is fast and wrong. Checked against a case whose exact
     p-value is known in closed form, plus the stopping rule's own invariants.
  d. a resumed parallel run that recomputes, double-counts, or silently drops a
     task. Plus: a worker that raises must name the failing feature/test upward.
"""

from __future__ import annotations

import datetime as _dt
import json
import math
import os

import numpy as np
import pytest

from engine import mine as M, mine_session as ms

SEED = 20260811
N_DAYS = 900
N_SURR = 40


# ------------------------------------------------------------------ fixtures ---
def _payload(n_feats=3, n_surr=N_SURR, ladder=None, seed=SEED):
    """A small but REAL payload: real ephemeris features, synthetic target."""
    t0 = _dt.datetime(2000, 1, 1)
    feats = M.ephemeris_features(t0, N_DAYS)[:n_feats]
    rng = np.random.default_rng(3)
    offset = np.full(N_DAYS, 5.0)
    counts = rng.poisson(offset).astype(np.float64)
    window = slice(0, N_DAYS)
    n_ev = 600
    day = np.sort(rng.integers(0, N_DAYS, size=n_ev))
    marks = {"day": day, "day_float": day + rng.random(n_ev),
             "mag": 4.5 + rng.exponential(0.4, n_ev),
             "depth": rng.uniform(0.0, 30.0, n_ev)}
    cfg = {"n_periods": 120, "n_peaks": 3, "seed": seed}
    return {
        "feats": {f.name: f for f in feats}, "window": window,
        "counts": counts, "offset": offset,
        "days": np.arange(N_DAYS, dtype=np.float64), "resid": counts - offset,
        "marks": marks, "fe_day": day - window.start,
        "seed": seed, "n_surr": n_surr, "ladder": ladder, "cfg": cfg,
        "period_chunk": M.PERIOD_SURROGATE_CHUNK,
    }


def _keys(W):
    return ([f"glm:{n}" for n in W["feats"]]
            + [f"marks:{n}" for n in W["feats"]]
            + ms.period_task_keys(W["cfg"], W["n_surr"]))


def _ckpt(tmp_path, name="session_x"):
    return ms.Checkpoint(str(tmp_path / name / "checkpoint.json"),
                         {"preset": "unit"}, "unit-hash")


