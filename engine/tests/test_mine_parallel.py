def test_jobs1_glm_is_bit_identical_to_the_v1_inner_loop():
    """The v1 GLM loop, restated here verbatim, must equal `glm_task`.

    This is the audit baseline. It is written out longhand ON PURPOSE: a golden
    JSON blob would pin the numbers but would not show a future reader WHAT the
    baseline was, and could be regenerated by whoever broke it.
    """
    W = _payload()
    counts, offset, window, n_surr = (W["counts"], W["offset"], W["window"],
                                      W["n_surr"])

    for f in W["feats"].values():
        # ---- v1, copied from mine_session.run() before the v2 refactor ----
        rng_v1 = np.random.default_rng(SEED)
        v1 = []
        for lag in f.lags:
            X = f.design(window, lag)
            fit = M.glm_fit(X, counts, offset)
            S = M.score_stat_all_shifts(X, counts, offset)
            p_shift, n_used = M.empirical_p(S, n_surr, rng_v1)
            Sb = M.score_stat_block_bootstrap(X, counts, offset, n_surr, rng_v1,
                                              mean_block=f.block_days)
            p_boot = M.bootstrap_p(S[0], Sb)
            p = p_boot if f.periodic else max(p_shift, p_boot)
            b = np.asarray(fit["beta"])
            amp = float(np.hypot(*b)) if f.kind == "phase" else float(abs(b[0]))
            v1.append({
                "feature": f.name, "family": f.family, "kind": f.kind,
                "lag": int(lag), "test": "glm_poisson_offset_etas", "df": f.df,
                "beta": fit["beta"], "se": fit["se"], "amplitude_log_rate": amp,
                "pct_rate_modulation": 100.0 * (math.exp(amp) - 1.0),
                "bits_per_event": fit["bits_per_event"],
                "chi2_score": float(S[0]), "p_parametric": M.chi2_sf(S[0], f.df),
                "p_circular_shift": p_shift, "p_block_bootstrap": p_boot,
                "block_days": f.block_days,
                "null": ("block-bootstrap (periodic feature)" if f.periodic
                         else "max(circular-shift, block-bootstrap)"),
                "p_raw": p, "n_surrogates": min(n_used, n_surr),
                "converged": fit["converged"],
            })

        # ---- v2, sequential path: the SAME shared-rng threading ----
        rng_v2 = np.random.default_rng(SEED)
        v2 = ms.glm_task(f, window, counts, offset, n_surr, lambda lag: rng_v2,
                         None, seed=SEED)
        assert json.dumps(v1, sort_keys=True) == json.dumps(v2, sort_keys=True), \
            f"--jobs 1 GLM output drifted from v1 for {f.name}"


def test_jobs1_marks_and_period_are_bit_identical_to_the_v1_inner_loops():
    W = _payload(n_feats=2)
    counts, offset, window = W["counts"], W["offset"], W["window"]
    marks, fe_day, n_surr = W["marks"], W["fe_day"], W["n_surr"]

    for f in W["feats"].values():
        rng_v1 = np.random.default_rng(SEED)
        vals = f.values[window][fe_day]
        v1 = []
        for mk in ("mag", "depth"):
            r = M.mark_test(vals, marks[mk], f.kind, n_surr, rng_v1)
            r.update({"feature": f.name, "family": f.family, "kind": f.kind,
                      "mark": mk, "n_events": int(marks[mk].size)})
            v1.append(r)
        rng_v2 = np.random.default_rng(SEED)
        v2 = ms.marks_task(f, window, fe_day, marks, n_surr, rng_v2, None,
                           seed=SEED)
        assert json.dumps(v1, sort_keys=True) == json.dumps(v2, sort_keys=True)

    # ---- period scan: PIN DELIBERATELY UPDATED IN v2 PHASE 1b ----
    # The v1 pin compared `period_scan` driven by a THREADED Generator against the
    # sequential driver threading the same one. That stream is gone on purpose: it
    # made the scan one indivisible task (90.7% of the sweep, Amdahl ceiling 1.10x)
    # and it was reproducible only for a single process running a fixed task order.
    # The replacement pin is stronger, not weaker -- it fixes the scan against the
    # KEY-DERIVED per-surrogate streams, which is a property of the seed alone and
    # holds across processes, chunkings and job counts (see the three phase-1b tests
    # at the bottom of this file).
    periods = np.exp(np.linspace(math.log(ms.PERIOD_MIN), math.log(ms.PERIOD_MAX),
                                 int(W["cfg"]["n_periods"])))
    peaks, meta = M.period_scan(W["days"], W["resid"], periods, n_surr, SEED,
                                n_peaks=int(W["cfg"]["n_peaks"]), verbose=False)
    v2 = ms.period_task(counts, offset, W["days"], W["resid"], W["cfg"], n_surr,
                        SEED, verbose=False)
    assert [p["period_days"] for p in v2["peaks"]] == [p["period_days"]
                                                       for p in peaks]
    assert [p["p_raw"] for p in v2["peaks"]] == [p["p_raw"] for p in peaks]
    assert v2["scan"]["ar1_phi"] == meta["ar1_phi"]
    # and the scan must refuse a threaded Generator outright rather than silently
    # accepting one and reintroducing order dependence
    with pytest.raises((TypeError, AttributeError, KeyError)):
        M.period_scan(W["days"], W["resid"], periods, n_surr,
                      np.random.default_rng(SEED), n_peaks=2, verbose=False)


def test_jobs_flag_is_absent_from_the_config_hash_and_ladder_is_present():
    """--jobs is execution; --ladder is statistics. The hash must say so."""
    from engine import splits

    class A:
        mag_target, dlat, dlon, explore_frac = 4.5, 0.5, 0.5, 0.7
        data_dir, no_download, seed, tranche1 = "engine/data", True, 1, False
        ladder = False
