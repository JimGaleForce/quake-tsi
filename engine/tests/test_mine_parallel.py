def test_ladder_rung_streams_cross_process_boundaries():
    """Popper's condition: rung 2 is rung 2 however the rungs were split up.

    Runs the rungs three ways -- both in one call, rung 2 alone, and rung 2 after
    rung 1 was drawn by a SEPARATE process -- and requires identical draws.
    """
    import concurrent.futures as cf
    import multiprocessing as mp

    rr = ms.rung_rng_factory(SEED, "moon_synodic_phase", "glm", 0,
                             null_type="block_bootstrap")
    one_process = [rr(0).random(5), rr(1).random(5), rr(2).random(5)]
    # rung 2 drawn on its own, with rungs 0 and 1 never drawn at all
    alone = rr(2).random(5)
    assert np.array_equal(one_process[2], alone)

    ctx = mp.get_context("spawn")
    with cf.ProcessPoolExecutor(max_workers=2, mp_context=ctx) as ex:
        got = list(ex.map(_draw_rung, [0, 1, 2]))
    for i in range(3):
        assert np.array_equal(one_process[i], got[i]), \
            f"rung {i} differs across a process boundary"


def _draw_rung(i):
    """Module-level (spawn-safe) helper for the cross-process rung test."""
    rr = ms.rung_rng_factory(SEED, "moon_synodic_phase", "glm", 0,
                             null_type="block_bootstrap")
    return rr(i).random(5)


def test_reduction_order_is_key_determined_not_arrival_determined():
    """BH and the ranked table must not depend on the order results arrive in."""
    rows = [{"p_raw": 0.5, "order_key": [0, 0, 0, 0, "a"]},
            {"p_raw": 0.5, "order_key": [0, 1, 0, 0, "b"]},
            {"p_raw": 0.01, "order_key": [0, 2, 0, 0, "c"]},
            {"p_raw": 0.5, "order_key": [1, 0, -1, 0, "d"]}]
    shuffled = [rows[2], rows[0], rows[3], rows[1]]
    a = sorted(rows, key=lambda t: t["order_key"])
    b = sorted(shuffled, key=lambda t: t["order_key"])
    assert a == b

    # BH itself must be order-invariant, ties included
    p = np.array([0.5, 0.5, 0.01, 0.5])
    perm = np.array([2, 0, 3, 1])
    q1, s1 = M.benjamini_hochberg(p, 0.1)
    q2, s2 = M.benjamini_hochberg(p[perm], 0.1)
    assert np.allclose(q1[perm], q2) and (s1[perm] == s2).all()


