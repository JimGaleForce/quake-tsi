def test_parallel_resume_skips_done_tasks_and_keeps_their_results(tmp_path):
    W = _payload(n_feats=2)
    keys = _keys(W)
    ck = _ckpt(tmp_path, "session_resume")

    # a "killed" run that got two tasks done
    first = keys[:2]
    n1 = ms._run_tasks_parallel(ck, first, W, 2, verbose=False)
    assert n1 == 2 and set(ck.state["results"]) == set(first)
    snapshot = json.dumps(ck.state["results"], sort_keys=True)

    # reload from disk exactly as a resumed invocation would
    again = ms.Checkpoint.load(ck.path)
    assert json.dumps(again.state["results"], sort_keys=True) == snapshot

    n2 = ms._run_tasks_parallel(again, keys, W, 3, verbose=False)
    assert n2 == len(keys) - 2, "resume recomputed already-checkpointed tasks"
    # per-task cost is recorded for every task the parent accepted, and survives
    # the reload -- so a resumed run can still be diagnosed
    assert set(again.state["task_seconds"]) == set(keys)
    assert set(again.state["results"]) == set(keys)
    # the survivors of the first run must be untouched, not recomputed
    for k in first:
        assert again.state["results"][k] == json.loads(snapshot)[k]
    # completed_tasks must not gain duplicates across the resume
    assert len(again.state["completed_tasks"]) == \
        len(set(again.state["completed_tasks"]))


