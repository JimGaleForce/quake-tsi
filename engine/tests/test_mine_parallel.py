def test_ladder_p_matches_a_known_closed_form_p():
    """A case whose p-value is known exactly, checked two ways.

    The observed statistic is placed at the exact q-quantile of a null we control,
    so the true exceedance probability IS q. The ladder's estimate must land on it,
    and the estimator's own spread must match the theory for h/l (whose relative SD
    is 1/sqrt(h)) -- a ladder that returned a constant would pass a mean check.
    """
    rng = np.random.default_rng(1234)
    for q in (0.5, 0.1, 0.02):
        s_obs = 1.0 - q                       # P(U(0,1) >= 1-q) = q, exactly
        est = []
        for i in range(400):
            ss = M.seed_sequence_for(
                M.test_key(SEED, f"known_{q}_{i}", "glm", lag=0, null_type="mc"))
            est.append(M.besag_clifford_p(
                lambda b, g: g.random(b), s_obs, n_max=5000,
                rung_rng=lambda r, _s=ss: np.random.default_rng(
                    M.rung_seed_sequence(_s, r)))["p"])
        est = np.array(est)
        # theory for the sequential estimator h/l: SD = q*sqrt((1-q)/h)
        sd_theory = q * math.sqrt((1.0 - q) / 25.0)
        se = sd_theory / math.sqrt(est.size)
        assert abs(est.mean() - q) < 5.0 * se, \
            f"ladder p mean {est.mean():.5f} != true q {q} (5 SE = {5 * se:.5f})"
        # the SPREAD must match the theory too: a rule that returned a constant,
        # or one that was secretly drawing far more than h exceedances, would pass
        # the mean check and fail here.
        assert 0.5 * sd_theory < est.std() < 2.0 * sd_theory, \
            (f"ladder p spread {est.std():.5f} does not match the h/l theory "
             f"{sd_theory:.5f} at q={q}")
    assert rng is not None


def test_ladder_stopping_rule_invariants():
    ss = M.seed_sequence_for(M.test_key(SEED, "inv", "glm", lag=0, null_type="mc"))

    def rr(r):
        return np.random.default_rng(M.rung_seed_sequence(ss, r))

    # early stop: p = h/l exactly, and l is the index of the h-th exceedance
    hot = M.besag_clifford_p(lambda b, g: g.random(b), 0.0, n_max=1000,
                             rung_rng=rr, h=25, chunk=200)
    assert hot["l_stop"] == 25 and hot["p"] == 25 / 25.0
    assert hot["p_basis"].startswith("h/l")

    # cap reached with c < h: the ordinary fixed-sample estimate, and NOT h/l
    cold = M.besag_clifford_p(lambda b, g: g.random(b), 2.0, n_max=1000,
                              rung_rng=rr, h=25, chunk=200)
    assert cold["l_stop"] is None and cold["n_exceed"] == 0
    assert cold["p"] == pytest.approx(1.0 / 1001.0)
    assert cold["n_drawn"] == 1000

    # chunk size is an implementation detail: it must not change the answer
    a = M.besag_clifford_p(lambda b, g: g.random(b), 0.9, n_max=2000, rung_rng=rr,
                           h=25, chunk=200)
    assert 0.0 < a["p"] <= 1.0
    # the h-th exceedance index must never exceed the number drawn
    assert a["l_stop"] is None or a["l_stop"] <= a["n_drawn"]
    with pytest.raises(ValueError):
        M.besag_clifford_p(lambda b, g: g.random(b), 0.5, n_max=10, rung_rng=rr,
                           h=0)


