    assert splits.config_hash(ms.build_config(a2, ms.QUICK)) == \
        splits.config_hash(base)
    assert "jobs" not in json.dumps(base)
    # and a default (ladder-off) config must be byte-identical to the v1 shape
    assert "ladder" not in base

    a3 = A()
    a3.ladder = True
    lad = ms.build_config(a3, ms.QUICK)
    assert lad["ladder"]["rule"] == "besag_clifford_1991"
    assert lad["ladder"]["h"] == 25
    assert lad["ladder"]["n_max"] == ms.QUICK["n_surrogates"]
    assert splits.config_hash(lad) != splits.config_hash(base), \
        "--ladder must change the config hash: it changes the sampling rule"

    a4 = A()
    a4.ladder, a4.ladder_h = True, 40
    assert splits.config_hash(ms.build_config(a4, ms.QUICK)) != \
        splits.config_hash(lad), "h must be part of the config hash"


